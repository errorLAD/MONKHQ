class ScriptVersion(models.Model):
    """
    Preserves version history of scripts when regenerated or revised.
    """
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    parent_script = models.ForeignKey(AIScript, on_delete=models.CASCADE, related_name='versions')
    version_number = models.IntegerField()
    hooks = models.JSONField(default=list)
    selected_hook = models.TextField(blank=True, default="")
    script_body = models.TextField()
    scenes = models.JSONField(default=list)
    caption = models.TextField(blank=True, default="")
    hashtags = models.CharField(max_length=500, blank=True, default="")
    cta = models.CharField(max_length=255, blank=True, default="")
    change_summary = models.CharField(max_length=255, default="Revised Version")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-version_number']

    def __str__(self):
        return f"Version {self.version_number} of {self.parent_script.title}"


class DiscoveredVideo(models.Model):
    """
    Discovered short-form content with breakout metrics from Viral Finder.
    """
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    workspace = models.ForeignKey(Workspace, on_delete=models.CASCADE, related_name='discovered_videos')
    video_id = models.CharField(max_length=255)
    source_provider = models.CharField(max_length=50, default="INSTAGRAM_GRAPH") # INSTAGRAM_GRAPH, MANUAL_INPUT, YOUTUBE_DATA, MOCK_TEST
    source_url = models.URLField(max_length=1000)
    thumbnail_url = models.URLField(max_length=1000, blank=True, default="")

    creator_name = models.CharField(max_length=255)
    creator_handle = models.CharField(max_length=255, blank=True, default="")
    creator_profile_url = models.URLField(max_length=1000, blank=True, default="")

    title = models.CharField(max_length=500, blank=True, default="")
    caption = models.TextField(blank=True, default="")
    transcript = models.TextField(blank=True, default="")

    niche = models.CharField(max_length=100, default="General")
    sub_niche = models.CharField(max_length=100, blank=True, default="")
    language = models.CharField(max_length=50, blank=True, default="English")
    published_at = models.DateTimeField(null=True, blank=True)

    views_count = models.BigIntegerField(default=0)
    likes_count = models.IntegerField(default=0)
    comments_count = models.IntegerField(default=0)
    shares_count = models.IntegerField(default=0)

    # Breakout Scoring
    creator_avg_views = models.BigIntegerField(default=0)
    breakout_score = models.DecimalField(max_digits=5, decimal_places=1, default=0.0) # e.g. 88.5
    breakout_ratio = models.DecimalField(max_digits=6, decimal_places=2, default=1.0) # e.g. 3.4x
    breakout_label = models.CharField(max_length=100, default="Consistent Performer")
    breakout_explanation = models.TextField(blank=True, default="")
    has_historical_baseline = models.BooleanField(default=False)

    retrieved_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-breakout_score', '-views_count']

    def __str__(self):
        return f"{self.title or self.caption[:50]} by @{self.creator_handle} (Score: {self.breakout_score})"


