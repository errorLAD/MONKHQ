class CreatorVoiceProfile(models.Model):
    """
    Personal writing-style profile for each creator.
    Used by AI Script Studio to personalize short-form scripts, hooks, and CTAs.
    """
    LANGUAGE_CHOICES = [
        ('ENGLISH', 'English'),
        ('HINDI', 'Hindi'),
        ('HINGLISH', 'Hinglish'),
    ]

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    workspace = models.ForeignKey(Workspace, on_delete=models.CASCADE, related_name='voice_profiles')
    creator = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name='voice_profiles')
    name = models.CharField(max_length=150, default="Primary Voice Persona")
    niche = models.CharField(max_length=100, blank=True, default="General")
    sub_niche = models.CharField(max_length=100, blank=True, default="")
    target_audience = models.CharField(max_length=255, blank=True, default="Social media creators & entrepreneurs")
    preferred_language = models.CharField(max_length=20, choices=LANGUAGE_CHOICES, default='ENGLISH')
    tone_of_voice = models.CharField(max_length=100, default="High-Energy & Direct")
    preferred_hook_style = models.CharField(max_length=100, default="Shocking Stat / Contrarian Question")
    typical_script_length = models.CharField(max_length=50, default="30-60s (Standard Reel)")
    common_content_themes = models.TextField(blank=True, default="Actionable tips, industry breakdowns, tutorials")
    preferred_cta_style = models.CharField(max_length=150, default="Comment 'FLOW' for the full breakdown")
    words_to_use = models.TextField(blank=True, default="listen up, game-changer, straight up, actionable, breakdown")
    words_to_avoid = models.TextField(blank=True, default="delve, tapestry, revolutionize, in conclusion, furthermore")
    ai_style_summary = models.TextField(blank=True, default="")
    is_active = models.BooleanField(default=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['-updated_at']

    def __str__(self):
        return f"{self.creator.username} - Voice: {self.name} ({self.tone_of_voice})"


