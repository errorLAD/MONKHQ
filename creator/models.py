    niche = models.CharField(max_length=100, blank=True, default="General")
    sub_niche = models.CharField(max_length=100, blank=True, default="")
    target_audience = models.CharField(max_length=255, blank=True, default="")
    language = models.CharField(max_length=20, default='ENGLISH') # ENGLISH, HINDI, HINGLISH
    platform = models.CharField(max_length=50, default='INSTAGRAM_REELS')
    duration = models.CharField(max_length=50, default='30-60s')
    objective = models.CharField(max_length=50, choices=OBJECTIVE_CHOICES, default='GROWTH')

    reference_notes = models.TextField(blank=True, default="")
    reference_video_url = models.URLField(max_length=1000, blank=True, default="")

    # AI Generated Outputs
    hooks = models.JSONField(default=list) # List of 5 hook options
    selected_hook = models.TextField(blank=True, default="")
    script_body = models.TextField() # Complete talking script
    scenes = models.JSONField(default=list) # Scene-by-scene breakdown
    on_screen_text = models.TextField(blank=True, default="")
    caption = models.TextField(blank=True, default="")
    hashtags = models.CharField(max_length=500, blank=True, default="")
    cta = models.CharField(max_length=255, blank=True, default="")
    filming_tips = models.TextField(blank=True, default="")

    version_number = models.IntegerField(default=1)
    is_saved = models.BooleanField(default=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['-updated_at']

